// L2 Cache Event Listeners for memory model checking

class L2DcacheReqEventListener(cachelineBytes: Int, sourceBits: Int) extends ExtModule with HasExtModuleInline {
  val io = IO(new Bundle {
    val source = Input(UInt(sourceBits.W))
    val opcode = Input(UInt(3.W))
    val paddr = Input(UInt(64.W))
    val data = Input(UInt((cachelineBytes * 8).W))
    val mask = Input(UInt(cachelineBytes.W))
    val enable = Input(Bool())
    val clock = Input(Clock())
    val reset = Input(Reset())
  })
  setInline("L2DcacheReqEventListener.sv",
    s"""
      |// generated by Chisel ExtModule
      |module L2DcacheReqEventListener(
      |  input [${sourceBits - 1}:0] io_source,
      |  input [2:0] io_opcode,
      |  input [63:0] io_paddr,
      |  input [${cachelineBytes * 8 - 1}:0] io_data,
      |  input [${cachelineBytes - 1}:0] io_mask,
      |  input io_enable,
      |  input io_clock,
      |  input io_reset
      |);
      |  import "DPI-C" function void dpi_l2_dcache_req_event(
      |    input longint source,
      |    input int opcode,
      |    input longint paddr,
      |    input int cacheline_size,
      |    input bit [${cachelineBytes * 8 - 1}:0] data,
      |    input bit [${cachelineBytes - 1}:0] mask
      |  );
      |
      |  always @(posedge io_clock) begin
      |    if (io_enable && !io_reset) begin
      |      dpi_l2_dcache_req_event({{${64 - sourceBits}{1'b0}}, io_source}, {29'b0, io_opcode}, io_paddr, ${cachelineBytes}, io_data, io_mask);
      |    end
      |  end
      |endmodule
      |""".stripMargin)
}

