# Regex to parse Scala BitPat definitions
# Matches: def NAME = BitPat("bSTRING")
# Example: def VADD_VV = BitPat("b000000???????????000?????1010111")
REGEX_INSTR = re.compile(r'def\s+(\w+)\s*=\s*BitPat\("b([01?]+)"\)')

def parse_bitpat(bitstr):
    """
    Parses a 32-char bit string (MSB at index 0).
    Returns dictionary with integer values for fixed fields, 
    and boolean flags for variable fields (operands).
    """
    if len(bitstr) != 32:
        raise ValueError(f"Bit string length {len(bitstr)} != 32")

    # RISC-V Vector Encoding Map (Indices in string, 0=MSB=Bit31)
    # Funct6: 0-6 (Bits 31-26)
    # VM    : 6   (Bit 25)
    # Rs2   : 7-12 (Bits 24-20)
    # Rs1   : 12-17 (Bits 19-15)
    # Funct3: 17-20 (Bits 14-12)
    # Rd    : 20-25 (Bits 11-7)
    # Opcode: 25-32 (Bits 6-0)

    def get_val(start, end):
        sub = bitstr[start:end]
        if '?' in sub: return None # Variable
        return int(sub, 2)

    def get_or_val(start, end):
        sub = bitstr[start:end]
        return int(sub.replace('?', '0'), 2)

    def is_var(start, end):
        return '?' in bitstr[start:end]

    info = {}
    info['opcode'] = get_val(25, 32)
    info['funct3'] = get_val(17, 20)
    assert info['opcode'] is not None, "Opcode must be fixed"
    assert info['funct3'] is not None, "Funct3 must be fixed"
    
    # Funct7 in vector is Funct6 + VM
    # If VM is ?, we default to 1 (unmasked) for the base opcode definition
    f6_str = bitstr[0:6]
    vm_str = bitstr[6]
    
    # Determine default funct7 value
    f6_val = int(f6_str.replace('?', '0'), 2) # Default ? to 0 for value calculation
    vm_val = 0 if vm_str == '?' else int(vm_str)
    info['funct7_val'] = (f6_val << 1) | vm_val

    # Operand detection
    info['has_rd']  = is_var(20, 25)
    info['hardcoded_rd'] = get_val(20, 25)
    info['has_rs1'] = is_var(12, 17) # vs1 or rs1 or imm or VWXUNARY0/VXUNARY0/VWFUNARY0/VFUNARY0/VFUNARY1/VMUNARY0
    info['hardcoded_rs1'] = get_val(12, 17)
    info['has_rs2'] = is_var(7, 12)  # vs2 or VRXUNARY0/VRFUNARY0
    info['hardcoded_rs2'] = get_val(7, 12)
    assert not info['has_rs1'] or bitstr[12:17]=='?????'
    assert not info['has_rs2'] or bitstr[7:12]=='?????'
    assert not info['has_rd'] or bitstr[20:25]=='?????'
    info['has_imm'] = False # None of the vector insn has imm, except VSETVLI etc, which are handled separately

    info['hardcoded_imm'] = get_or_val(0, 12)
    info['has_vm']  = (vm_str == '?')

    info['vm_hardcoded'] = vm_val if (vm_str != '?') else None # 0 if vmasked is enabled
    
    return info

def classify_instruction(name, info, bitstr):
    """
    Determines Format, Category, and Lambda Signature based on Name and BitPat.
    """
    # 1. Determine Category
    if name.startswith("VL") or name.startswith("VLE") or name.startswith("VLO") or name.startswith("VLU"):
        cat = CAT_LOAD
    elif name.startswith("VS") and not name.startswith("VSET") and not name.startswith("VSL") and not name.startswith("VSR") and not name.startswith("VSSUB") and not name.startswith("VSUB") and not name.startswith("VSMUL") and not name.startswith("VSGN") and not name.startswith("VSADD") and not name.startswith("VSEXT") and not "VSLL" in name and not "VSLIDE" in name:
        cat = CAT_STORE
    elif name.startswith("VAMO"):
        cat = CAT_AMO
    elif name.startswith("VSET"):
        cat = CAT_SYS
    elif name.startswith("CSR"):
        cat = CAT_CSR
    elif name in ['VAND_VI', 'VAND_VV', 'VAND_VX', 'VOR_VI', 'VOR_VV', 'VOR_VX', 'VXOR_VI', 'VXOR_VV', 'VXOR_VX']:
        cat = CAT_LOGIC
    elif "_MM" in name or "_M" in name or name in ['JOIN', 'BARRIER', 'BARRIERSUB', 'ENDPRG', 'SETRPC']:
        cat = CAT_TMASKCTRL
    elif '_VIM' in name or '_VVM' in name or '_VXM' in name or name in ['VFMV_F_S', 'VFMV_S_F', 'VFMV_V_F']: # but 'VMV_S_X', 'VMV_V_I', 'VMV_V_V', 'VMV_V_X', 'VMV_X_S' are not merge-type
        cat = CAT_THREAD_MERGE
    elif name in ['VMFEQ_VF', 'VMFEQ_VV', 'VMFGE_VF', 'VMFGT_VF', 'VMFLE_VF', 'VMFLE_VV', 'VMFLT_VF', 'VMFLT_VV', 'VMFNE_VF', 'VMFNE_VV', 'VMSEQ_VI', 'VMSEQ_VV', 'VMSEQ_VX', 'VMSGT_VI', 'VMSGT_VX', 'VMSGTU_VI', 'VMSGTU_VX', 'VMSLE_VI', 'VMSLE_VV', 'VMSLE_VX', 'VMSLEU_VI', 'VMSLEU_VV', 'VMSLEU_VX', 'VMSLT_VV', 'VMSLT_VX', 'VMSLTU_VV', 'VMSLTU_VX', 'VMSNE_VI', 'VMSNE_VV', 'VMSNE_VX']:
        cat = CAT_COMPARE
    elif name in ['VBEQ', 'VBGE', 'VBGEU', 'VBLT', 'VBLTU', 'VBNE']:
        cat = CAT_BRANCH
    elif name in ['REGEXT', 'REGEXTI']:
        cat = CAT_REG_CTRL
    elif name in ['VFTTA_VV']:
        cat = CAT_TENSOR
    else:
        __builtins__.print(name)
        cat = CAT_ARITH

    # 2. Determine Format and Lambda Type
    # Heuristics based on suffix and operand presence
    
    fmt = FORMAT_VVV # Default
    cb_type = "riscv_gen_R_VVV"
    is_ventus_store = False
    is_ventus_load = False
    # Lambda args: vd, vs1, vs2. 
    # Mapped to instruc_rtype: (op, vd, f3, vs1, vs2, f7)
    
    if name == 'VADD12_VI' or name == 'VSUB12_VI':
        fmt = FORMAT_I_VV
        cb_type = "riscv_gen_I_VV"
        info['has_vm'] = False
        info['has_imm'] = True

    elif cat == CAT_BRANCH or name == "JOIN": # vector only
        fmt = FORMAT_B_VV
        cb_type = "riscv_gen_B_VV"
        info['has_vm'] = False
        info['has_imm'] = True

    elif name == 'REGEXT' or name == 'REGEXTI':
        fmt = FORMAT_I
        cb_type = "riscv_gen_I"
        info['has_vm'] = False
        info['has_imm'] = True
        info['has_rs1'] = False
        info['hardcoded_rs1'] = 0
        info['has_rd'] = False
        info['hardcoded_rd'] = 0

    elif name == 'ENDPRG':
        fmt = FORMAT_R
        cb_type = "riscv_gen_R"
        info['has_vm'] = False

    elif name in ['BARRIER', 'BARRIERSUB']:
        fmt = FORMAT_I_UIMM_CSR
        cb_type = "riscv_gen_I_UIMM_CSR"
        info['has_vm'] = False
        info['hardcoded_rs1'] = 0b00000 # uimm
        info['has_rs1'] = False
        info['hardcoded_rd'] = 0b00000
        info['has_rs2'] = False
        info['has_rd'] = False
        info['has_imm'] = False

    elif name == 'SETRPC':
        fmt = FORMAT_I
        cb_type = "riscv_gen_I"
        info['has_vm'] = False
        info['hardcoded_rd'] = 0b00000
        info['has_rd'] = False
        info['has_imm'] = True

    elif ("_VI" in name or "_V_I" in name) and "VSET" not in name:
        fmt = FORMAT_VIV
        cb_type = "riscv_gen_R_VIV"
        # Lambda args: vd, imm, vs2
        # Mapped to instruc_rtype: (op, vd, f3, imm, vs2, f7)
        
    elif "_VX" in name or "_V_X" in name or "_VF" in name or "_V_F" in name:
        fmt = FORMAT_VXV
        cb_type = "riscv_gen_R_VXV"
        # Lambda args: vd, rs1, vs2
        # Mapped to instruc_rtype: (op, vd, f3, rs1, vs2, f7)

    elif cat == CAT_LOAD:
        if name == 'VLSE32_V':
            fmt = FORMAT_VXX
            cb_type = "riscv_gen_R_VXX"
        elif name in ['VLW12_V',
    'VLH12_V',
    'VLB12_V',
    'VLHU12_V',
    'VLBU12_V']:
            # ventus loads
            fmt = FORMAT_I_VV
            cb_type = "riscv_gen_I_VV"
            info['has_vm'] = False
            info['has_imm'] = True
            is_ventus_load = True
        elif name in [
    'VLW_V',
    'VLH_V',
    'VLB_V',
    'VLHU_V',
    'VLBU_V']:
            # ventus loads
            fmt = FORMAT_I_VX
            cb_type = "riscv_gen_I_VX"
            info['has_vm'] = False
            info['has_imm'] = True
            is_ventus_load = True

        else:
            # Vector Loads: Dest=V(rd), Base=X(rs1), Mask/Mop=V(rs2/vm)
            # We need a format that accepts Vector Dest and Scalar Src.
            # R_VXV fits: vd (Vector), rs1 (Scalar), vs2 (Vector/Mask).
            fmt = FORMAT_VXV 
            cb_type = "riscv_gen_R_VXV"
        
    elif cat == CAT_STORE:
        if name == 'VSSE32_V':
            fmt = FORMAT_VXX
            cb_type = "riscv_gen_R_VXX"
        elif name in ['VSW12_V',
    'VSH12_V',
    'VSB12_V']:
            # ventus stores
            fmt = FORMAT_S_VV
            cb_type = "riscv_gen_S_VV"
            is_ventus_store = True
        elif name in ['VSW_V',
    'VSH_V',
    'VSB_V']:
            # ventus stores
            fmt = FORMAT_S_XV
            cb_type = "riscv_gen_S_XV"
            is_ventus_store = True
        else:
            # Vector Stores: Data=V(vs3/rd), Base=X(rs1), Mask/Mop=V(rs2/vm)
            # Store uses 'rd' field for data source (vs3).
            # We can use R_VXV: vd (mapped to vs3), rs1 (base), vs2 (mask).
            fmt = FORMAT_VXV
            cb_type = "riscv_gen_R_VXV"

    elif name.startswith("VMV_X_S") or name.startswith("VFMV_F_S"):
        # Move Vector to Scalar: Rd=X, Vs2=V.
        # R_XXV: rd, rs1, vs2. We can use this, set rs1 to 0.
        fmt = FORMAT_XXV
        cb_type = "riscv_gen_R_XXV"
        
    elif name.startswith("VMV_S_X") or name.startswith("VFMV_S_F"):
        # Move Scalar to Vector: Vd=V, Rs1=X.
        # R_VXV: vd, rs1, vs2. Set vs2 to 0.
        fmt = FORMAT_VXV
        cb_type = "riscv_gen_R_VXV"
        
    elif name.startswith("VSET"):
        # VSETVLI: Rd=X, Rs1=X, Imm(vtype).
        # I_FORMAT: rd, rs1, imm (used as vtype?).
        if name == 'VSETVLI':
            fmt = FORMAT_I
            cb_type = "riscv_gen_I"
            info['has_imm'] = True
        elif name == 'VSETIVLI':
            fmt = FORMAT_I_UIMM_CSR
            cb_type = "riscv_gen_I_UIMM_CSR"
            info['has_imm'] = True
        elif name == 'VSETVL':
            fmt = FORMAT_R
            cb_type = 'riscv_gen_R'
        else:
            assert False

    elif "_VV" in name or "_V_V" in name or "_MM" in name or "_M" in name:
        fmt = FORMAT_VVV
        cb_type = "riscv_gen_R_VVV"
    
    else:
        __builtins__.print('Using default VVV for ' + name)
    
    # TODO: vmsif vmsof vmsbf vcpop vfirst vreadffr (currently unused)

    if fmt == FORMAT_VIV:
        info['has_imm'] = True
    
    if (info['has_imm'] and
      # VIV using rs1 field for imm
      fmt != FORMAT_VIV and
      # BRANCH use imm that does't overlap with rs2
      fmt != FORMAT_B_VV):
        info['has_rs2'] = False

    # encoding format for scalar (or some extended vector) instructions do not have VM bit
    if fmt in [FORMAT_I, FORMAT_I_UIMM_CSR, FORMAT_S_VV, FORMAT_S_XV, FORMAT_B_VV, FORMAT_I_VV, FORMAT_R]:
        info['has_vm'] = False
    
    if fmt in [FORMAT_S_VV, FORMAT_S_XV]:
        info['has_rd'] = False
        info['has_imm'] = True
    
    if fmt in [FORMAT_B_VV]:
        info['has_rd'] = False
        info['has_imm'] = True
        assert info['has_rs1']
        assert info['has_rs2'], f"{bitstr[7:12]}"

    if name == 'JOIN' or name == 'ENDPRG':
        info['hardcoded_rd'] = 0b00000
        info['hardcoded_rs1'] = 0b00000
        info['hardcoded_rs2'] = 0b00000
        info['has_rs1'] = False
        info['has_rs2'] = False
        info['has_rd'] = False
        info['hardcoded_imm'] = 0
        info['has_imm'] = False

    has_mop = has_mew = has_nf = False
    nf_range = None
    if (not is_ventus_load and cat == CAT_LOAD) or (not is_ventus_store and cat == CAT_STORE):
        # MOP
        if '?' in bitstr[31-27:31-26+1]:
            #__builtins__.print('mop ', name)
            assert bitstr[31-27:31-26+1]=='??', f'{name} {bitstr[31-27:31-26+1]}'
            has_mop = True
        # mew
        if '?' in bitstr[31-28]:
            #__builtins__.print('mew ', name)
            has_mew = True
        # nf
        if '?' in bitstr[31-31:31-29+1]:
            #__builtins__.print('nf ', name)
            has_nf = True
            if bitstr[31-31:31-29+1] == '0??':
                nf_range = 0
            elif bitstr[31-31:31-29+1] == '1??':
                nf_range = 1
            elif bitstr[31-31:31-29+1] == '???':
                nf_range = 2
            else:
                assert False, bitstr[31-31:31-29+1]
        
        if has_nf or has_mew or has_mop:
            if fmt == FORMAT_VXV:
                if cat == CAT_STORE:
                    fmt = FORMAT_V3XV_MOP_MEW_NF
                    cb_type = 'riscv_gen_R_V3XV_MOP_MEW_NF'
                else:
                    fmt = FORMAT_VXV_MOP_MEW_NF
                    cb_type = 'riscv_gen_R_VXV_MOP_MEW_NF'
            elif fmt == FORMAT_VXX:
                if cat == CAT_STORE:
                    fmt = FORMAT_V3XX_MOP_MEW_NF
                    cb_type = 'riscv_gen_R_V3XX_MOP_MEW_NF'
                else:
                    fmt = FORMAT_VXX_MOP_MEW_NF
                    cb_type = 'riscv_gen_R_VXX_MOP_MEW_NF'
            else:
                assert False
    info.update({'has_mop': has_mop,
            'has_mew': has_mew,
            'has_nf': has_nf,
            'has_mop_mew_nf': has_mop or has_mew or has_nf,
            'nf_range': nf_range,
            })

    return fmt, cat, cb_type, info

def generate_cpp_code(bittable, supported, isa_ext_name, instr_fn, meta_fn):
    instructions = []
    
    # Parse file
    for match in REGEX_INSTR.finditer(bittable):
        name = match.group(1)
        bitstr = match.group(2)
        
        # Filter: Only process Vector instructions
        # Heuristic: Name starts with 'V' and is not a standard extension scalar instr (like 'W' or 'F' that might overlap, though usually distinct).
        # Also check opcode. Vector Opcode is usually ...111.
        # Instructions.scala contains scalar instructions too (ADD, SUB).
        if not name.startswith("V") and name not in ['SETRPC',
    'BARRIER',
    'BARRIERSUB',
    'ENDPRG',
    'REGEXT',
    'REGEXTI',
    'SETRPC',
    'JOIN']:
            continue
        
        # Exclude some potentially false positives if necessary, but "V" is usually safe for RVV.
        # Note: 'VID' is parsed as 'VID_V' in the file provided.
        
        #try:
        if 1:
            info = parse_bitpat(bitstr)
        #except Exception as e:
        #    print(f"// Error parsing {name}: {e}")
        #    continue

        if name not in supported:
            continue  # Unsupported insn

        fmt, cat, cb_type, info = classify_instruction(name, info, bitstr)

        instr_data = {
            'name': name,
            'fmt': fmt,
            'cat': cat,
            'cb_type': cb_type,
        }
        instr_data.update(info) 
       
        instructions.append(instr_data)

    fp = open(instr_fn, 'w')
    def new_print(s) : fp.write(s + '\n')
    print = new_print
    print("// ==========================================")
    print("// Auto-generated RISC-V Vector Instructions")
    print("// ==========================================")
    print("""#include "isa/riscv/riscv_encode.hh"
#include "isa/riscv/riscv_meta_list.hh"

namespace fuzzgpu {
""")
    print(f"void riscv_meta_list::register_{isa_ext_name}() {{")
    print("")

    vm_hardcoded_insn = []
    for i in instructions:
        # Construct the lambda body based on format
        # instruc_rtype(opcode, rd, funct3, rs1, rs2, funct7)
        
        # Handle Funct3 (Variable or Fixed)
        val_f3 = f"0b{i['funct3']:03b}" if i['funct3'] is not None else "0" # If ? (unlikely for F3), 0.
        
        # Handle Funct7 (Variable or Fixed)
        val_f7 = f"0b{i['funct7_val']:07b}"
        
        # Handle Opcode
        val_op = f"0b{i['opcode']:07b}"

        arg_vm = ''
        if i['cb_type'] == "riscv_gen_R_VVV":
            # (vd, vs1, vs2)
            var_arg0 = 'vd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'vs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'vs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == "riscv_gen_R_VXV":
            # (vd, rs1, vs2)
            var_arg0 = 'vd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'vs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == "riscv_gen_R_VXV_MOP_MEW_NF":
            # (vd, rs1, vs2)
            var_arg0 = 'vd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'vs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == "riscv_gen_R_V3XV_MOP_MEW_NF":
            # (vs3, rs1, vs2)
            var_arg0 = 'vs3'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'vs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == "riscv_gen_R_VIV":
            # (vd, imm, vs2)
            var_arg0 = 'vd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'imm'
            arg1 = f"int64_t {var_arg1}" # Immediate maps to rs1 field (5 bits)
            var_arg2 = 'vs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == "riscv_gen_R_XXV":
            # (rd, rs1, vs2)
            var_arg0 = 'rd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'vs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == "riscv_gen_I":
            var_arg0 = 'rd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'imm'
            arg2 = f"int64_t {var_arg2}"
        elif i['cb_type'] == 'riscv_gen_I_UIMM_CSR':
            var_arg0 = 'rd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'uimm'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'csr'
            arg2 = f"uint32_t {var_arg2}"
        elif  i['cb_type'] == 'riscv_gen_R':
            var_arg0 = 'rd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'rs2'
            arg2 = f"uint32_t {var_arg2}"
        elif i['cb_type'] == 'riscv_gen_R_VXX':
            var_arg0 = 'vd'
            arg0 = f"uint32_t {var_arg0}"
            var_arg1 = 'rs1'
            arg1 = f"uint32_t {var_arg1}"
            var_arg2 = 'rs2'
